const configFile = '.github/ljharb-actions.json';

/** @type {(ignore: unknown, extra?: Record<string, unknown>) => string} */
function pkgWith(ignore, extra = { devDependencies: { npmignore: '^0.3.1' } }) {
	return `${JSON.stringify({
		name: 'pkg', ...extra, publishConfig: { ignore },
	}, null, 2)}\n`;
}

/** @type {(text: string) => string} */
function crlf(text) {
	return text.replace(/\n/g, '\r\n');
}

/** @type {(synced: { content: string } | null) => unknown} */
function ignoreOf(synced) {
	return synced === null ? null : JSON.parse(synced.content).publishConfig.ignore;
}

test('usesNpmignore', (t) => {
	t.ok(usesNpmignore({ dependencies: { npmignore: '*' } }), 'a dependency');
	t.ok(usesNpmignore({ devDependencies: { npmignore: '*' } }), 'a dev dependency');
	t.notOk(usesNpmignore({ peerDependencies: { npmignore: '*' } }), 'not a peer dependency');
	t.notOk(usesNpmignore({ dependencies: null, devDependencies: ['npmignore'] }), 'nor anything that isn’t an object of dependencies');

	[
		'npmignore --auto --commentLines=autogenerated',
		'npx npmignore --auto',
		'npx npmignore@^0.3 --auto',
		'npm run build && npmignore',
		'echo hi;npmignore',
		'(npmignore)',
		'npx "npmignore@^0.3" --auto',
	].forEach((script) => {
		t.ok(usesNpmignore({ scripts: { prepack: script } }), `a script that runs it: \`${script}\``);
	});
	[
		'rm .npmignore',
		'cat .npmignore',
		'my-npmignore',
		'npmignored',
		'node npmignore.js',
		'echo dir/npmignore',
	].forEach((script) => {
		t.notOk(usesNpmignore({ scripts: { prepack: script } }), `not a script that only mentions it: \`${script}\``);
	});
	t.notOk(usesNpmignore({ scripts: { prepack: ['npmignore'] } }), 'nor a script that isn’t a string');
	t.notOk(usesNpmignore({ scripts: 'npmignore' }), 'nor `scripts` that isn’t an object');
	t.notOk(usesNpmignore({}), 'nor no mention at all');

	t.end();
});

test('syncConfigIgnore: when the config file will exist', async (t) => {
	t.deepEqual(ignoreOf(await syncConfigIgnore(pkgWith(['.github/workflows', 'test']), true)), ['.github/workflows', configFile, 'test'], 'added right after `.github/workflows`');
	t.deepEqual(ignoreOf(await syncConfigIgnore(pkgWith(['test', '/.github/workflows/', '.github/workflows', 'x']), true)), ['test', '/.github/workflows/', configFile, '.github/workflows', 'x'], 'after the first one, however it’s written');
	t.deepEqual(ignoreOf(await syncConfigIgnore(pkgWith(['test', 'coverage']), true)), ['test', 'coverage', configFile], 'otherwise, at the end');
	t.deepEqual(ignoreOf(await syncConfigIgnore(pkgWith([]), true)), [configFile], 'including to an empty array');
	t.deepEqual(ignoreOf(await syncConfigIgnore(pkgWith(['!.github/workflows', 'x']), true)), ['!.github/workflows', 'x', configFile], 'a re-included `.github/workflows` isn’t one to add it after');
	t.deepEqual(ignoreOf(await syncConfigIgnore(pkgWith([1, null, '.github/workflows']), true)), [1, null, '.github/workflows', configFile], 'entries that aren’t strings are skipped');
	t.deepEqual(ignoreOf(await syncConfigIgnore(pkgWith(['.github/workflows', { a: 1 }, [2], { b: 2 }]), true)), ['.github/workflows', configFile, { a: 1 }, [2], { b: 2 }], 'and those after it are kept as they are, not merged into what was where they move to');

	t.deepEqual(ignoreOf(await syncConfigIgnore(pkgWith(['.github', '!.github', 'x']), true)), ['.github', '!.github', 'x', configFile], 'a `.github` re-included by a later `!` doesn’t ignore it');
	t.deepEqual(ignoreOf(await syncConfigIgnore(pkgWith(['.github/workflows', '.github', '!/.github/']), true)), ['.github/workflows', '.github', '!/.github/', configFile], 'and it’s added after that `!`, which would otherwise re-include it too');

	t.deepEqual(ignoreOf(await syncConfigIgnore(pkgWith([`${configFile}/`, `/${configFile}/`]), true)), [`${configFile}/`, `/${configFile}/`, configFile], 'the file itself with a trailing `/` matches only a directory of that name, so doesn’t ignore it');
	t.deepEqual(ignoreOf(await syncConfigIgnore(pkgWith(['.github', `!${configFile}/`]), true)), null, 'nor, after a `!`, re-include it');
	t.deepEqual(ignoreOf(await syncConfigIgnore(pkgWith([`!${configFile}/`]), true)), [`!${configFile}/`, configFile], 'so it doesn’t say it’s meant to be published');

	await Promise.all([
		[[configFile], 'the file itself'],
		[[`/${configFile}`], 'the file itself, with a leading `/`'],
		[['.github'], '`.github`'],
		[['.github/'], '`.github/`'],
		[['/.github'], '`/.github`'],
		[['.github', '!.github', '.github'], '`.github`, ignored again after a `!`'],
		[['.github', `!${configFile}`], 'a `!` that re-includes the file itself, which says it’s meant to be published'],
		[[`!${configFile}`, '.github'], 'even when something later ignores it again'],
	].map(async ([ignore, what]) => {
		t.equal(await syncConfigIgnore(pkgWith(ignore), true), null, `no change when it’s already covered: ${what}`);
	}));

	t.equal(await syncConfigIgnore(pkgWith(['test'], {}), true), null, 'no change when the package doesn’t use `npmignore`');
	t.deepEqual(ignoreOf(await syncConfigIgnore(pkgWith(['test'], { scripts: { prepack: 'npmignore --auto' } }), true)), ['test', configFile], 'a script that runs it is enough');
	t.equal(await syncConfigIgnore(`${JSON.stringify({ devDependencies: { npmignore: '*' } })}\n`, true), null, 'no change without `publishConfig`');
	t.equal(await syncConfigIgnore(`${JSON.stringify({ devDependencies: { npmignore: '*' }, publishConfig: [] })}\n`, true), null, 'nor with one that isn’t an object');
	t.equal(await syncConfigIgnore(`${JSON.stringify({ devDependencies: { npmignore: '*' }, publishConfig: { registry: 'x' } })}\n`, true), null, 'nor without `publishConfig.ignore`');
	t.equal(await syncConfigIgnore(pkgWith('.github/workflows'), true), null, 'nor with one that isn’t an array');
	t.equal(await syncConfigIgnore(null, true), null, 'no change without a `package.json`');
	t.equal(await syncConfigIgnore('{ nope', true), null, 'nor with one that isn’t JSON');
	t.equal(await syncConfigIgnore('', true), null, 'nor an empty one');
	t.equal(await syncConfigIgnore('[1]', true), null, 'nor one that’s an array');
	t.equal(await syncConfigIgnore('"npmignore"', true), null, 'nor a string');

	const tabbed = '{\n\t"name": "pkg",\n\t"devDependencies": {\n\t\t"npmignore": "^0.3.1"\n\t},\n\t"publishConfig": {\n\t\t"ignore": [\n\t\t\t".github/workflows",\n\t\t\t"test"\n\t\t]\n\t},\n\t"version": "1.0.0"\n}\n';
	t.deepEqual(await syncConfigIgnore(tabbed, true), { content: tabbed.replace('".github/workflows",\n', `".github/workflows",\n\t\t\t"${configFile}",\n`), reason: 'ignored' }, 'keeping its indentation, its keys’ order, and its trailing newline');
	t.deepEqual(await syncConfigIgnore(`${pkgWith(['test'])}\n`, true), { content: `${pkgWith(['test', configFile])}\n`, reason: 'ignored' }, 'and a trailing blank line');

	t.deepEqual(await syncConfigIgnore(crlf(pkgWith(['.github/workflows', 'test'])), true), { content: crlf(pkgWith(['.github/workflows', configFile, 'test'])), reason: 'ignored' }, 'and its `\\r\\n` line endings, throughout');

	const pkg = pkgWith(['.github/workflows']);
	await Promise.all([
		[pkg.replace('\n', '\r\n'), 'mostly `\\n` line endings, and a `\\r\\n`'],
		[crlf(pkg).replace('\r\n', '\n'), 'mostly `\\r\\n` line endings, and a `\\n`'],
		[pkg.trimEnd(), 'no final newline'],
		[`${JSON.stringify(JSON.parse(pkg))}\n`, 'minified'],
		[pkg.replace('[\n      ".github/workflows"\n    ]', '[".github/workflows"]'), 'an array on one line'],
		[pkg.replace('"pkg"', '"p\\u006bg"'), 'an escape `JSON.stringify` doesn’t write'],
		[pkg.replace('  "name"', '\t"name"'), 'mixed indentation'],
	].map(async ([text, what]) => {
		t.equal(await syncConfigIgnore(text, true), null, `no change when \`json-file-plus\` wouldn’t write it as it is, so other lines would change too: ${what}`);
	}));

	t.end();
});

test('syncConfigIgnore: when the config file won’t exist', async (t) => {
	t.deepEqual(await syncConfigIgnore(pkgWith(['.github/workflows', configFile, 'test']), false), { content: pkgWith(['.github/workflows', 'test']), reason: 'unignored' }, 'its entry is removed');
	t.deepEqual(ignoreOf(await syncConfigIgnore(pkgWith([configFile]), false)), [], 'even its only one');
	t.deepEqual(ignoreOf(await syncConfigIgnore(pkgWith([`/${configFile}`, 'test', configFile, '/.github/']), false)), ['test', '/.github/'], 'every one, with or without a leading `/`');
	t.deepEqual(ignoreOf(await syncConfigIgnore(pkgWith([configFile, `${configFile}/`, `/${configFile}/`]), false)), [`${configFile}/`, `/${configFile}/`], 'but not one with a trailing `/`, which matches only a directory of that name, so isn’t its entry');
	t.deepEqual(ignoreOf(await syncConfigIgnore(pkgWith([1, configFile, null, `!${configFile}`]), false)), [1, null, `!${configFile}`], 'keeping entries that aren’t strings, and a `!` that re-includes it');
	t.deepEqual(ignoreOf(await syncConfigIgnore(pkgWith(['.github', configFile]), false)), ['.github'], 'and `.github`, which ignores more than it');
	t.deepEqual(ignoreOf(await syncConfigIgnore(pkgWith(['test', configFile], { scripts: { prepack: 'npmignore --auto' } }), false)), ['test'], 'a script that runs `npmignore` is enough');

	await Promise.all([
		[['.github', 'test'], 'only `.github` covers it'],
		[['.github/', '.github/*.json', `!${configFile}`, `${configFile}.bak`, `.github/workflows/${configFile}`], 'nothing is exactly it'],
		[[], 'it’s empty'],
	].map(async ([ignore, what]) => {
		t.equal(await syncConfigIgnore(pkgWith(ignore), false), null, `no change when ${what}`);
	}));

	t.equal(await syncConfigIgnore(pkgWith([configFile], {}), false), null, 'no change when the package doesn’t use `npmignore`');
	t.equal(await syncConfigIgnore(pkgWith(configFile), false), null, 'nor when `publishConfig.ignore` isn’t an array');
	t.equal(await syncConfigIgnore(null, false), null, 'nor without a `package.json`');
	t.equal(await syncConfigIgnore('{ nope', false), null, 'nor with one that isn’t JSON');

	t.deepEqual(await syncConfigIgnore(crlf(pkgWith(['.github/workflows', configFile, 'test'])), false), { content: crlf(pkgWith(['.github/workflows', 'test'])), reason: 'unignored' }, 'keeping its `\\r\\n` line endings, throughout');

	const pkg = pkgWith(['.github/workflows', configFile]);
	await Promise.all([
		[pkg.replace('\n', '\r\n'), 'mostly `\\n` line endings, and a `\\r\\n`'],
		[crlf(pkg).replace('\r\n', '\n'), 'mostly `\\r\\n` line endings, and a `\\n`'],
		[pkg.trimEnd(), 'no final newline'],
		[`${JSON.stringify(JSON.parse(pkg))}\n`, 'minified'],
		[pkg.replace(`[\n      ".github/workflows",\n      "${configFile}"\n    ]`, `[".github/workflows", "${configFile}"]`), 'an array on one line'],
	].map(async ([text, what]) => {
		t.equal(await syncConfigIgnore(text, false), null, `no change when \`json-file-plus\` wouldn’t write it as it is, so other lines would change too: ${what}`);
	}));

	t.end();
});

test('packageJsonAt and hasConfig', (t) => {
	const dir = tempDir(t, 'fleet-npmignore');
	git(dir, ['init', '--quiet', '--initial-branch=main']);
	/** @type {Git} */
	const run = (args, options) => exec('git', args, {
		cwd: dir, env: gitIsolation, ...options,
	});
	/** @type {(files: Record<string, string | null>) => string} */
	const commit = (files) => {
		writeFiles(dir, files);
		git(dir, ['add', '--all']);
		git(dir, ['commit', '--quiet', '--allow-empty', '--message', 'change']);
		return git(dir, ['rev-parse', 'HEAD']);
	};

	const none = commit({ 'README.md': 'hi\n' });
	t.equal(packageJsonAt(run, none), null, 'no `package.json`');
	t.equal(hasConfig(run, none), false, 'no config file');

	const regular = commit({ 'package.json': '{}\n', [configFile]: '{}\n' });
	t.equal(packageJsonAt(run, regular), '{}\n', 'a regular file’s text');
	t.equal(hasConfig(run, regular), true, 'a config file');

	chmodSync(path.join(dir, 'package.json'), 0o755);
	const executable = commit({});
	t.equal(packageJsonAt(run, executable), null, 'not an executable one');

	writeFiles(dir, { 'package.json': null });
	symlinkSync('README.md', path.join(dir, 'package.json'));
	const link = commit({});
	t.equal(packageJsonAt(run, link), null, 'nor a symbolic link');

	t.end();
});
